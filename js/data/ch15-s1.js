<p>十五世纪的意大利艺术家有两个互相矛盾的目标。一个是要把人物画「对」——透视准确、解剖正确、衣褶有重量；另一个是要画面「好看」——人物在画面上排布得有节奏、有图案感。这两个目标经常打架：人画得越准，构图越容易散；构图越整齐，人越像摆上去的。</p>

